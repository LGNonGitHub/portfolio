#!/usr/bin/env node
/**
 * Builds src/lib/kanji/strokes.json: the stroke-order paths KanjiWrite draws
 * each section kanji with.
 *
 * Source: KanjiVG by Ulrich Apel (https://kanjivg.tagaini.net), CC BY-SA 3.0.
 * Each KanjiVG file lists one <path id="kvg:XXXXX-sN"> per stroke, in the order
 * the stroke is written, so document order IS the stroke order — nothing here
 * re-sorts or edits the geometry. The output is a derived work and therefore
 * stays a separate, share-alike data file with its own LICENSE next to it; it
 * is never inlined into the site's own (differently licensed) source.
 *
 * Which characters: every character of nav[].jp in src/lib/content.ts, plus
 * 剣 and 杖 (the duality pair). Reading nav from the source rather than a list
 * here means renaming a section's kanji only needs `npm run kanji`.
 *
 * Usage:  node scripts/build-kanji.mjs [--from=<dir of cached KanjiVG svgs>]
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'src/lib/kanji');
const EXTRA = ['剣', '杖'];
const fromArg = process.argv.find((a) => a.startsWith('--from='));
const fromDir = fromArg ? path.resolve(fromArg.slice('--from='.length)) : null;

/** The nav array is plain object literals, so a regex is enough — and it keeps
 *  this script free of a TypeScript loader. */
async function navKanji() {
  const src = await readFile(path.join(root, 'src/lib/content.ts'), 'utf8');
  const block = src.match(/export const nav = \[([\s\S]*?)\] as const;/);
  if (!block) throw new Error('Could not find `export const nav` in content.ts');
  const chars = [];
  for (const m of block[1].matchAll(/jp:\s*'([^']+)'/g)) chars.push(...m[1]);
  if (!chars.length) throw new Error('nav[] has no jp labels');
  return chars;
}

const hex = (ch) => ch.codePointAt(0).toString(16).padStart(5, '0');

async function loadSvg(ch) {
  const name = `${hex(ch)}.svg`;
  if (fromDir && existsSync(path.join(fromDir, name))) {
    return readFile(path.join(fromDir, name), 'utf8');
  }
  const url = `https://raw.githubusercontent.com/KanjiVG/kanjivg/master/kanji/${name}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${ch} (${name}): HTTP ${res.status} from ${url}`);
  return res.text();
}

/** Stroke paths in document order. Attribute order differs between KanjiVG
 *  releases, so id and d are matched independently inside each <path>. */
function strokes(svg, ch) {
  const id = hex(ch);
  const out = [];
  for (const tag of svg.matchAll(/<path\b[^>]*>/g)) {
    const t = tag[0];
    const sid = t.match(/\bid="kvg:([0-9a-f]{5})-s(\d+)"/);
    if (!sid || sid[1] !== id) continue;
    const d = t.match(/\bd="([^"]+)"/);
    if (d) out.push(d[1].trim());
  }
  return out;
}

const chars = [...new Set([...(await navKanji()), ...EXTRA])];
const data = {
  _license:
    'KanjiVG (c) Ulrich Apel, CC BY-SA 3.0 — derived stroke data, same licence',
};
for (const ch of chars) {
  const list = strokes(await loadSvg(ch), ch);
  if (!list.length) throw new Error(`${ch}: no kvg stroke paths found`);
  data[ch] = list;
  console.log(`${ch}  U+${hex(ch).toUpperCase()}  ${list.length} strokes`);
}

await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, 'strokes.json'), JSON.stringify(data) + '\n');

